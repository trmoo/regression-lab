import { h } from '../lib/ui.js';
import { 빈칸칸, 고르기, 확인상자, 서술칸 } from '../lib/widgets.js';
import { 문장 } from '../data.js';
import { 카드, 머리, 개념 } from './common.js';

export function 그리기() {
  const 빈칸영역 = 개념(
    h('p', {}, '- ', 빈칸칸('c-cor'), ': 한 변수의 변화에 따라 다른 변수도 변화하는 관계'),
    h('p', {}, '- ', 빈칸칸('c-cau'), ': 어떤 변수가 다른 변수의 원인이 되는 관계'),
    h('p', {}, '- 인과관계는 상관관계에서 원인과 결과의 관계까지 밝히지만, ', h('b', {}, '상관관계만으로는 인과 관계를 밝힐 수 없다.')));

  const 문장영역 = h('table', { class: 'grid-table' },
    h('thead', {}, h('tr', {}, h('th', {}, '문장'), h('th', {}, '어느 쪽일까?'))),
    h('tbody', {}, 문장.map((q, i) => h('tr', {},
      h('td', {}, `${'①②③④⑤'[i]} ${q.글}`),
      h('td', {}, 고르기(q.id, [{ 값: '상관', 글: '상관관계만 있다' }, { 값: '인과', 글: '인과 관계도 있다' }], { 작게: true }))))));

  return [
    머리('2', '상관관계와 인과관계'),
    카드('개념 채우기', 빈칸영역, 확인상자('s2-blanks', 빈칸영역)),
    카드('▣ 상관관계만 있을까, 인과관계도 있을까?',
      h('p', { class: 'muted' }, '「한쪽을 바꾸면 다른 쪽이 바뀌는가?」를 따져 보세요.'),
      문장영역,
      확인상자('s2-sent', 문장영역, { 해설: (id) => 문장.find((q) => q.id === id)?.해설 })),
    카드('▣ 숨은 원인 찾기',
      서술칸('hidden'),
      h('details', { class: 'deeper' },
        h('summary', {}, '🔍 숨은 원인을 그림으로 보기 (예: ③)'),
        h('div', { class: 'hidden-cause' },
          h('div', { class: 'box cause' }, '☀️ 더운 날씨'),
          h('div', { class: 'branches' },
            h('div', {}, h('span', { class: 'arr' }, '➜ 원인 ➜'), h('span', { class: 'box' }, '❄️ 에어컨 판매량 ↑')),
            h('div', {}, h('span', { class: 'arr' }, '➜ 원인 ➜'), h('span', { class: 'box' }, '🍉 수박 판매량 ↑')))),
        h('p', {}, '에어컨과 수박은 함께 늘어나지만(상관관계) 서로가 원인은 아니다. 에어컨을 더 판다고 수박이 더 팔리지는 않는다.'))),
  ];
}
