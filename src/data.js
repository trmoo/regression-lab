/** 띄어쓰기·괄호·마침표를 걷어 내고 비교한다. 빼기는 하이픈으로 맞춘다. */
export function 다듬기(글) {
  return String(글 ?? '')
    .trim()
    .replace(/[−–—]/g, '-')
    .replace(/[\s().,·「」'"]/g, '')
    .toLowerCase();
}

/** 빈칸 하나 채점 */
export function 빈칸맞나(id, 값) {
  const 정 = 빈칸[id];
  if (!정) throw new Error(`없는 빈칸: ${id}`);
  const v = 다듬기(값);
  if (!v) return false;
  return 정.답.some((a) => 다듬기(a) === v);
}

/** 숫자 칸 채점 — 허용 오차 안이면 맞음 */
export function 숫자맞나(값, 정답, 허용 = 0.01) {
  const 글 = String(값 ?? '').trim().replace(/[−–—]/g, '-').replace(/,/g, '');
  if (글 === '' || 글 === '-') return false;
  const v = Number(글);
  return Number.isFinite(v) && Math.abs(v - 정답) <= 허용;
}
